use anyhow::{bail, Context, Result};
use clap::Parser;
use resolve_cli::{Agent, run_prompt, run_critique, prepare_output_path, require_file};
use std::fs;
use std::path::PathBuf;

const ANALYZE_PROMPT_TEMPLATE: &str = include_str!("../../prompts/input-synthesis-reachability-analyze.txt");
const CRITIQUE_NEGATION: &str = include_str!("../../prompts/input-synthesis-reachability-critique-negation.txt");
const SYNTHESIS_FROM_REACHABILITY_TEMPLATE: &str = include_str!("../../prompts/input-synthesis-synthesis-from-reachability.txt");

#[derive(Parser)]
#[command(
    name = "resolve-input-synthesis-reachability",
    about = "Run a reachability analysis pipeline on conditions generated by improve_CVE. \
             The pipeline performs an initial analysis followed by a challenge/revise pass. \
             All intermediate artifacts are written under a unique /tmp workspace and final results are copied to output_path.",
    after_help = "Examples:\n  resolve-input-synthesis-reachability codex cve.json out/improve_cve out/reachability\n  resolve-input-synthesis-reachability claude cve.json out/improve_cve out/reachability"
)]
struct Args {
    /// Coding agent backend to execute prompts with
    #[arg(value_parser = ["claude", "codex", "opencode"])]
    agent: String,

    /// Path to the input CVE file
    cve_path: PathBuf,

    /// Output directory from improve_CVE containing condition documents
    improve_cve_path: PathBuf,

    /// Destination directory for final artifacts
    output_path: PathBuf,

    /// Optional model override passed through to the selected agent CLI
    #[arg(long)]
    model: Option<String>,

    /// Overwrite output_path if it already exists
    #[arg(long)]
    overwrite: bool,
}

fn run(args: Args) -> Result<()> {
    let agent = Agent::from_str(&args.agent)?;

    let cve = fs::read_to_string(&args.cve_path)
        .with_context(|| format!("Failed to read CVE file: {}", args.cve_path.display()))?;

    if !args.improve_cve_path.is_dir() {
        bail!("improve_cve_path is not a directory: {}", args.improve_cve_path.display());
    }

    let necessary_conditions_path = args.improve_cve_path.join("necessary_conditions");
    let sufficient_conditions_path = args.improve_cve_path.join("sufficient_conditions");
    
    if !necessary_conditions_path.is_dir() {
        bail!("missing directory: {}", necessary_conditions_path.display());
    }
    if !sufficient_conditions_path.is_dir() {
        bail!("missing directory: {}", sufficient_conditions_path.display());
    }

    if !necessary_conditions_path.read_dir()?.any(|e| {
        e.ok().map(|e| {
            e.file_name().to_string_lossy().starts_with("NC_") &&
            e.file_name().to_string_lossy().ends_with(".md")
        }).unwrap_or(false)
    }) {
        println!("warning: no NC_*.md files in {}", necessary_conditions_path.display());
    }
    
    if !sufficient_conditions_path.read_dir()?.any(|e| {
        e.ok().map(|e| {
            e.file_name().to_string_lossy().starts_with("SC_") &&
            e.file_name().to_string_lossy().ends_with(".md")
        }).unwrap_or(false)
    }) {
        println!("warning: no SC_*.md files in {}", sufficient_conditions_path.display());
    }

    prepare_output_path(&args.output_path, args.overwrite)?;

    let reachability_path = args.output_path.join("reachability.md");
    let critique_path = args.output_path.join("critique_scratch");
    fs::create_dir_all(&critique_path)?;

    // Canonicalize paths for prompts
    let necessary_conditions_path_abs = necessary_conditions_path.canonicalize()
        .with_context(|| format!("Failed to resolve necessary conditions path"))?;
    let sufficient_conditions_path_abs = sufficient_conditions_path.canonicalize()
        .with_context(|| format!("Failed to resolve sufficient conditions path"))?;
    let output_path_abs = args.output_path.canonicalize()
        .with_context(|| format!("Failed to create and resolve output path: {}", args.output_path.display()))
        .or_else(|_| {
            // If canonicalize fails, the directory might not exist yet
            fs::create_dir_all(&args.output_path)?;
            args.output_path.canonicalize()
                .with_context(|| format!("Failed to resolve output path after creation"))
        })?;
    let reachability_path_abs = output_path_abs.join("reachability.md");

    ////////////////////////////////////////////////////////////////////////////
    // REACHABILITY ANALYSIS
    ////////////////////////////////////////////////////////////////////////////

    let analyze_prompt = ANALYZE_PROMPT_TEMPLATE
        .replace("{CVE}", &cve)
        .replace("{NECESSARY_CONDITIONS_PATH}", &necessary_conditions_path_abs.display().to_string())
        .replace("{SUFFICIENT_CONDITIONS_PATH}", &sufficient_conditions_path_abs.display().to_string())
        .replace("{REACHABILITY_PATH}", &reachability_path_abs.display().to_string());

    run_prompt(agent, &analyze_prompt, args.model.as_deref())?;
    require_file(&reachability_path, "reachability analysis")?;

    ////////////////////////////////////////////////////////////////////////////
    // REACHABILITY CRITIQUE
    ////////////////////////////////////////////////////////////////////////////

    let reachability_content = fs::read_to_string(&reachability_path)
        .with_context(|| format!("Failed to read reachability file: {}", reachability_path.display()))?;

    let critique_preamble = format!(
        "# CVE\n\n{}\n\n# Reachability analysis\n\n{}",
        cve,
        reachability_content
    );

    let critique_path_abs = critique_path.canonicalize()
        .with_context(|| format!("Failed to resolve critique path"))?;

    run_critique(
        agent,
        &critique_preamble,
        CRITIQUE_NEGATION,
        &critique_path_abs,
        &reachability_path_abs,
        args.model.as_deref(),
    )?;
    require_file(&reachability_path, "reachability critique")?;

    ////////////////////////////////////////////////////////////////////////////
    // INPUT SYNTHESIS AND CONCLUSION
    ////////////////////////////////////////////////////////////////////////////

    let final_prompt = SYNTHESIS_FROM_REACHABILITY_TEMPLATE
        .replace("{REACHABILITY_PATH}", &reachability_path_abs.display().to_string())
        .replace("{OUTPUT_PATH}", &output_path_abs.display().to_string());

    run_prompt(agent, &final_prompt, args.model.as_deref())?;
    
    let conclusion_path = args.output_path.join("conclusion.md");
    require_file(&conclusion_path, "final conclusion")?;

    Ok(())
}

fn main() {
    let args = Args::parse();
    
    if let Err(e) = run(args) {
        eprintln!("Error: {:#}", e);
        std::process::exit(1);
    }
}
